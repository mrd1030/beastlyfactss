// Chronicles series slug prefixes (mirrors CHRONICLES_SERIES in src/lib/chronicles.js).
// Their stories render on /chronicles/<id>/<part>, not /blog/<slug> - the old
// blog URLs 301 in public/_redirects.
const CHRONICLES_PREFIXES = { dex: 'chronicles-of-dex', otis: 'chronicles-of-otis' };
const isChroniclesSlug = (slug) =>
  Object.values(CHRONICLES_PREFIXES).some(prefix => slug.startsWith(prefix));

// Mirrors slugify in src/lib/utils/slugify.js (incl. the "&"/"and" rule that
// makes "Small & Exotic Pets" produce "small-and-exotic-pets").
const slugifyCategory = (text) => text.toString().toLowerCase()
  .replace(/\s*&\s*|\s+and\s+/g, '-and-')
  .replace(/\s+/g, '-')
  .replace(/[^a-z0-9-]/g, '')
  .replace(/-+/g, '-')
  .replace(/^-|-$/g, '');

// Blog post routes, one per MDX post. Chronicles posts are excluded by slug
// prefix (not by category tag) so this can't silently break if the "Short
// Stories" category gets renamed/re-slugged - they render on /chronicles/
// instead, and their old /blog/ URLs 301 in public/_redirects.
function getMdxRoutes(meta) {
  return meta
    .filter(post => !isChroniclesSlug(post.slug))
    .map(post => `/blog/${post.slug}`);
}

// Blog category pages, one per category that actually has at least one post -
// Blog.jsx renders a pill for each of those, so they need prerendered pages or
// the pill links 404 on a hard load.
// /category/X 301s to /blog/category/X in _redirects (retired duplicate route) - don't prerender it.
function getMdxCategoryRoutes(meta) {
  const routes = new Set();
  for (const post of meta) {
    // Every category the post is filed under, not just the primary one, so a
    // post tagged both Aquatic Life and Wild Animals prerenders under each.
    const cats = (post.categories?.length ? post.categories : [post.category]).filter(Boolean);
    for (const cat of cats) {
      const slug = slugifyCategory(cat);
      // site-news 301s to the welcome post; short-stories 301s to /chronicles/
      if (!slug || slug === 'site-news' || slug === 'short-stories') continue;
      routes.add(`/blog/category/${slug}`);
    }
  }
  return [...routes];
}

// Chronicles part routes: /chronicles/<series> (part 1) plus /chronicles/<series>/<n>.
// Parts = the MDX short-story posts per series - must stay consistent with
// groupChronicles() in src/lib/chronicles.js.
function getChroniclesRoutes(meta) {
  const slugs = [...new Set(meta.map(post => post.slug).filter(isChroniclesSlug))];

  const routes = [];
  for (const [id, prefix] of Object.entries(CHRONICLES_PREFIXES)) {
    const partCount = slugs.filter(s => s.startsWith(prefix)).length;
    routes.push(`/chronicles/${id}`); // landing list
    for (let n = 1; n <= partCount; n++) routes.push(`/chronicles/${id}/${n}`);
  }
  return routes;
}

